// Полномочия председателя совета без кворума (п. 13.2 и 13.4 устава).
//
// Устав позволяет передать председателю право единолично решать вопросы
// подпунктов а)–и) пункта 13.4, когда у совета нет кворума. Набор выбирают
// учредители. Подпункт ж) («приостановление полномочий Председателя Совета…»)
// зависит от выбора: если председателю переданы а) или е), подпункт ж)
// исключается, а буквы подпунктов после него сдвигаются (з → ж … с → р).
// Сам подпункт ж) председателю не передаётся — он о самом председателе.
//
// Общий модуль для генератора (заполнение онлайн) и scripts/make-samples.mjs
// (шаблон для скачивания: как в прежней редакции — только б), ж) остаётся).

// Подпункты 13.4, которые можно передать председателю, с кратким смыслом
export const CHAIR_OPTIONS = [
  ['а', 'созыв, подготовка и проведение Общих собраний'],
  ['б', 'приём в пайщики по заявлениям'],
  ['в', 'организация выполнения наказов пайщиков'],
  ['г', 'эффективное использование трудовых, материальных и финансовых ресурсов'],
  ['д', 'разработка и утверждение положений и инструкций, в том числе по займам пайщикам'],
  ['е', 'назначение и увольнение заместителей председателя, правления и руководителей подразделений'],
  ['з', 'определение полномочий правления и контроль за ним'],
  ['и', 'перечень информации, составляющей коммерческую тайну'],
]

export const DEFAULT_CHAIR_POWERS = ['б']

// Подпункты, передача которых исключает подпункт ж)
const EXCLUDE_ZH = ['а', 'е']
const ORDER = ['а', 'б', 'в', 'г', 'д', 'е', 'ж', 'з', 'и', 'к', 'л', 'м', 'н', 'о', 'п', 'р', 'с']
// Поля шаблона для букв после ж)
const AFTER_ZH = { з: 'l_z', и: 'l_i', к: 'l_k', л: 'l_l', м: 'l_m', н: 'l_n', о: 'l_o', п: 'l_p', р: 'l_r', с: 'l_s' }

export function keepsZh(selected) {
  return !selected.some((l) => EXCLUDE_ZH.includes(l))
}

// Данные для шаблона устава
export function chairPowersData(selected = DEFAULT_CHAIR_POWERS) {
  const allowed = new Set(CHAIR_OPTIONS.map(([l]) => l))
  const chosen = ORDER.filter((l) => selected.includes(l) && allowed.has(l))
  const zh = keepsZh(chosen)
  // Итоговая буква подпункта: без ж) всё после него сдвигается на одну
  const final = (l) => {
    const i = ORDER.indexOf(l)
    return !zh && i > ORDER.indexOf('ж') ? ORDER[i - 1] : l
  }
  const letters = chosen.map((l) => `${final(l)})`)
  const list = letters.length > 1 ? `${letters.slice(0, -1).join(', ')} и ${letters[letters.length - 1]}` : letters[0] || ''
  const data = {
    chair_has: chosen.length > 0,
    chair_abzac: letters.length > 1 ? `абзацах ${list}` : `абзаце ${list}`,
    council_suspend: zh,
  }
  for (const [l, tag] of Object.entries(AFTER_ZH)) data[tag] = final(l)
  return data
}
