// Наименование организационно-правовой формы кооператива для всех документов.
//
// Основа — «Потребительское Общество» (рекомендация владельца, 16.11.2026):
// регистрируем потребительское общество. К основе можно дописать продолжение,
// например «взаимного обеспечения» или «открытых систем»; сами слова
// «Потребительское Общество» остаются всегда.
//
// Поля шаблонов:
//   full_abbr          — полное наименование формы: «Потребительское Общество …»
//   full_abbr_genitive — родительный падеж: «Потребительского Общества …»
//   full_abbr_dative   — предложный падеж: «Потребительском Обществе …»
//   big_full_abbr      — заглавными: «ПОТРЕБИТЕЛЬСКОЕ ОБЩЕСТВО …»
//   short_abbr         — первые буквы слов полного наименования: «ПО», «ПОВО»
// Продолжение пишется как есть: оно обычно уже стоит в родительном падеже
// («взаимного обеспечения») и при склонении основы не меняется.

const BASE = { full: 'Потребительское Общество', genitive: 'Потребительского Общества', dative: 'Потребительском Обществе' }

export function orgFormData(tail = '') {
  const t = (tail || '').trim().replace(/\s+/g, ' ')
  const add = (s) => (t ? `${s} ${t}` : s)
  const full = add(BASE.full)
  return {
    full_abbr: full,
    full_abbr_genitive: add(BASE.genitive),
    full_abbr_dative: add(BASE.dative),
    big_full_abbr: full.toUpperCase(),
    short_abbr: full
      .split(/[\s-]+/)
      .filter(Boolean)
      .map((w) => w[0].toUpperCase())
      .join(''),
  }
}
